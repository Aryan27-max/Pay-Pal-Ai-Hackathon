import { db } from "@/lib/db";
import { poolSummary, usd } from "@/lib/ledger";
import { SIMULATED_EVENT } from "@/lib/disasters";
import { serviceEnabled } from "@/lib/services";
import { explorerTxUrl } from "@/lib/trail";

/**
 * The PUBLIC transparency feed (/api/trail, /dashboard). Redacted by construction: public ids (HMAC),
 * ~10 km geo cells, amounts, statuses, PayPal batch/capture ids and Solana signatures. Never an email,
 * name, message, transcript, photo, exact GPS or a reviewer's free-text reason (only its hash, on chain).
 */
export type TrailRef = { status: string; signature: string | null; url: string | null; memo: string | null } | null;

function eventLabel(id: string | null): string {
  if (!id) return "no active event";
  if (id === SIMULATED_EVENT.id) return SIMULATED_EVENT.name.replace(/\s*\(SIMULATED[^)]*\)/i, "");
  if (id.startsWith("gdacs:")) return `GDACS ${id.split(":")[1]} event ${id.split(":")[2]}`;
  if (id.startsWith("usgs:")) return `USGS earthquake ${id.slice(5)}`;
  return id;
}

export async function publicFeed() {
  const [summary, donations, claims, decisions, payouts, trail] = await Promise.all([
    poolSummary(),
    db.donation.findMany({ orderBy: { createdAt: "desc" }, take: 200 }),
    db.claim.findMany({ orderBy: { createdAt: "desc" }, take: 200, select: { claimPublicId: true, geoCell: true, disasterEventId: true, eventSource: true, status: true, score: true, createdAt: true, updatedAt: true } }),
    db.decision.findMany({ orderBy: { createdAt: "desc" }, take: 300, include: { claim: { select: { claimPublicId: true } } } }),
    db.payout.findMany({
      orderBy: { createdAt: "desc" },
      take: 200,
      include: { claim: { select: { claimPublicId: true, geoCell: true, disasterEventId: true } }, allocations: { include: { donation: { select: { donorPublicId: true } } } } },
    }),
    db.trailEntry.findMany({ orderBy: { createdAt: "desc" }, take: 500 }),
  ]);
  const byRef = new Map(trail.map((t) => [`${t.kind}:${t.refId}`, t]));
  const ref = (kind: string, id: string): TrailRef => {
    const t = byRef.get(`${kind}:${id}`);
    if (!t) return null;
    return { status: t.status, signature: t.status === "CONFIRMED" ? t.signature : null, url: t.status === "CONFIRMED" && t.signature ? explorerTxUrl(t.signature) : null, memo: t.memo };
  };
  const counts = (s: string[]) => claims.filter((c) => s.includes(c.status)).length;

  return {
    generatedAt: new Date().toISOString(),
    pool: {
      donatedUsd: usd(summary.donatedCents),
      paidOutUsd: usd(summary.paidOutCents),
      availableUsd: usd(summary.availableCents),
      donations: summary.donations,
      claims: claims.length,
      peoplePaid: counts(["PAID", "ON_CHAIN"]),
      inReview: counts(["IN_REVIEW"]),
      rejected: counts(["REJECTED"]),
      waiting: counts(["WAITING_FUNDS", "APPROVED", "PAYOUT_PENDING"]),
    },
    trail: {
      enabled: serviceEnabled(process.env, "solana"),
      confirmed: trail.filter((t) => t.status === "CONFIRMED").length,
      queued: trail.filter((t) => ["PENDING", "SENDING", "SENT"].includes(t.status)).length,
      failed: trail.filter((t) => t.status === "FAILED").length,
      memoFormat: "RS|v1|<type>|<public_id>|<amount_usd>|<sha256 of row_json>",
    },
    donations: donations.map((d) => ({
      at: d.createdAt.toISOString(),
      donor: d.donorPublicId,
      amountUsd: usd(Math.round(Number(d.amountUsd) * 100)),
      remainingUsd: usd(Math.round(Number(d.remainingUsd) * 100)),
      paypalCaptureId: d.paypalCaptureId,
      source: d.source,
      trail: ref("donation", d.id),
    })),
    claims: claims.map((c) => ({
      at: c.createdAt.toISOString(),
      claim: c.claimPublicId,
      cell: c.geoCell,
      event: eventLabel(c.disasterEventId),
      simulatedEvent: c.eventSource === "simulated",
      status: c.status,
      score: c.score,
    })),
    decisions: decisions.map((d) => ({
      at: d.createdAt.toISOString(),
      claim: d.claim.claimPublicId,
      actor: d.actor === "engine" ? "engine" : "reviewer",
      outcome: d.outcome,
      score: d.score,
      // Engine reasons are generated by code (no PII); reviewer text stays private (its hash is on chain).
      reason: d.actor === "engine" ? d.reason : "reviewer decision (reason kept private; its sha256 is in the on-chain record)",
      trail: ref("decision", d.id),
    })),
    payouts: payouts.map((p) => ({
      at: p.createdAt.toISOString(),
      claim: p.claim.claimPublicId,
      cell: p.claim.geoCell,
      event: eventLabel(p.claim.disasterEventId),
      simulatedEvent: p.claim.disasterEventId === SIMULATED_EVENT.id,
      amountUsd: usd(Math.round(Number(p.amountUsd) * 100)),
      status: p.status,
      paypalPayoutBatchId: p.payoutBatchId,
      fundedBy: p.allocations.map((a) => ({ donor: a.donation.donorPublicId, amountUsd: usd(Math.round(Number(a.amountUsd) * 100)) })),
      trail: ref("payout", p.id),
    })),
    trailEntries: trail.slice(0, 100).map((t) => ({
      at: t.createdAt.toISOString(),
      type: t.type,
      publicId: t.publicId,
      amountUsd: t.amountUsd,
      memo: t.memo,
      rowSha256: t.rowSha256,
      rowJson: t.rowJson,
      status: t.status,
      mode: t.mode,
      signature: t.status === "CONFIRMED" ? t.signature : null,
      url: t.status === "CONFIRMED" && t.signature ? explorerTxUrl(t.signature) : null,
    })),
  };
}

export type PublicFeed = Awaited<ReturnType<typeof publicFeed>>;
